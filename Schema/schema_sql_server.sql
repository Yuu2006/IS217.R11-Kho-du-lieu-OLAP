-- Khoi tao bang DIM: khoa chinh la ma/gia tri nguon; chi DIM_RESTAURANT va DIM_OUTCOME dung khoa so.
CREATE TABLE DIM_DATE (
    FULL_DATE DATE NOT NULL PRIMARY KEY,
    DAY_OF_MONTH TINYINT NOT NULL,
    MONTH_NUMBER TINYINT NOT NULL,
    QUARTER_NUMBER TINYINT NOT NULL,
    YEAR_NUMBER SMALLINT NOT NULL,
    WEEKDAY_NUMBER TINYINT NOT NULL,
    IS_WEEKEND BIT NOT NULL
);

CREATE TABLE DIM_TIME (
    HOUR_NUMBER TINYINT NOT NULL PRIMARY KEY,
    DAY_PART NVARCHAR(20) NOT NULL
);

-- Ma nha hang nguon khong duy nhat (mot ma nam o 2 subzone) nen dung khoa so RESTAURANT_ID.
CREATE TABLE DIM_RESTAURANT (
    RESTAURANT_ID INT NOT NULL PRIMARY KEY,
    SOURCE_RESTAURANT_ID INT NOT NULL,
    SUBZONE NVARCHAR(100) NOT NULL,
    RESTAURANT_NAME NVARCHAR(100) NOT NULL,
    CITY NVARCHAR(100) NOT NULL,
    CONSTRAINT UQ_DIM_RESTAURANT_NK UNIQUE (SOURCE_RESTAURANT_ID, SUBZONE)
);

CREATE TABLE DIM_CUSTOMER (
    SOURCE_CUSTOMER_ID NVARCHAR(64) NOT NULL PRIMARY KEY
);

CREATE TABLE DIM_ITEM (
    ITEMS_IN_ORDER NVARCHAR(200) NOT NULL PRIMARY KEY
);

-- O trong cua ly do / nhan khieu nai duoc ghi la 'Not recorded' (khong phai "khong co su co").
CREATE TABLE DIM_OUTCOME (
    OUTCOME_ID INT NOT NULL PRIMARY KEY,
    ORDER_STATUS NVARCHAR(40) NOT NULL,
    ORDER_READY_MARKED NVARCHAR(40) NOT NULL,
    CANCELLATION_REJECTION_REASON NVARCHAR(100) NOT NULL,
    CUSTOMER_COMPLAINT_TAG NVARCHAR(100) NOT NULL,
    CONSTRAINT UQ_DIM_OUTCOME_NK UNIQUE
        (ORDER_STATUS, ORDER_READY_MARKED, CANCELLATION_REJECTION_REASON, CUSTOMER_COMPLAINT_TAG)
);

-- Don khong khuyen mai duoc ghi la 'None'.
CREATE TABLE DIM_PROMOTION (
    DISCOUNT_CONSTRUCT NVARCHAR(100) NOT NULL PRIMARY KEY,
    PROMOTION_TYPE NVARCHAR(30) NOT NULL
);

CREATE TABLE DIM_DISTANCE (
    DISTANCE NVARCHAR(20) NOT NULL PRIMARY KEY,
    DISTANCE_INT TINYINT NOT NULL
);
-- Khoi tao bang FACT
CREATE TABLE FACT_ORDER (
    SOURCE_ORDER_ID BIGINT NOT NULL PRIMARY KEY,
    FULL_DATE DATE NOT NULL REFERENCES DIM_DATE(FULL_DATE),
    HOUR_NUMBER TINYINT NOT NULL REFERENCES DIM_TIME(HOUR_NUMBER),
    RESTAURANT_ID INT NOT NULL REFERENCES DIM_RESTAURANT(RESTAURANT_ID),
    SOURCE_CUSTOMER_ID NVARCHAR(64) NOT NULL REFERENCES DIM_CUSTOMER(SOURCE_CUSTOMER_ID),
    OUTCOME_ID INT NOT NULL REFERENCES DIM_OUTCOME(OUTCOME_ID),
    DISCOUNT_CONSTRUCT NVARCHAR(100) NOT NULL REFERENCES DIM_PROMOTION(DISCOUNT_CONSTRUCT),
    DISTANCE NVARCHAR(20) NOT NULL REFERENCES DIM_DISTANCE(DISTANCE),
    BILL_SUBTOTAL DECIMAL(14,2) NOT NULL,
    PACKAGING_CHARGES DECIMAL(14,2) NOT NULL,
    DISCOUNT_TOTAL DECIMAL(14,2) NOT NULL,
    TOTAL DECIMAL(14,2) NOT NULL,
    RATING_VALUE DECIMAL(3,1) NULL,
    KPT_MINUTES DECIMAL(8,2) NULL,
    RIDER_WAIT_MINUTES DECIMAL(8,2) NULL
);
-- Khoi tao bang BRIDGE
CREATE TABLE BRIDGE_ORDER_ITEM (
    SOURCE_ORDER_ID BIGINT NOT NULL REFERENCES FACT_ORDER(SOURCE_ORDER_ID),
    ITEMS_IN_ORDER NVARCHAR(200) NOT NULL REFERENCES DIM_ITEM(ITEMS_IN_ORDER),
    ITEM_QUANTITY INT NOT NULL CHECK (ITEM_QUANTITY > 0),
    CONSTRAINT PK_BRIDGE_ORDER_ITEM PRIMARY KEY (SOURCE_ORDER_ID, ITEMS_IN_ORDER)
);

CREATE INDEX IX_FACT_ORDER_DATE ON FACT_ORDER(FULL_DATE);
CREATE INDEX IX_FACT_ORDER_RESTAURANT ON FACT_ORDER(RESTAURANT_ID);
CREATE INDEX IX_FACT_ORDER_CUSTOMER ON FACT_ORDER(SOURCE_CUSTOMER_ID);
CREATE INDEX IX_FACT_ORDER_OUTCOME ON FACT_ORDER(OUTCOME_ID);
CREATE INDEX IX_BRIDGE_ORDER_ITEM_ITEM ON BRIDGE_ORDER_ITEM(ITEMS_IN_ORDER);
