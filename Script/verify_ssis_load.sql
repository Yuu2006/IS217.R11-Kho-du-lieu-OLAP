SELECT TABLE_NAME, ACTUAL_ROWS, EXPECTED_ROWS,
       CASE WHEN ACTUAL_ROWS = EXPECTED_ROWS THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'DIM_DATE' AS TABLE_NAME, COUNT_BIG(*) AS ACTUAL_ROWS, 153 AS EXPECTED_ROWS FROM dbo.DIM_DATE
    UNION ALL SELECT 'DIM_TIME', COUNT_BIG(*), 18 FROM dbo.DIM_TIME
    UNION ALL SELECT 'DIM_RESTAURANT', COUNT_BIG(*), 24 FROM dbo.DIM_RESTAURANT
    UNION ALL SELECT 'DIM_CUSTOMER', COUNT_BIG(*), 11607 FROM dbo.DIM_CUSTOMER
    UNION ALL SELECT 'DIM_OUTCOME', COUNT_BIG(*), 34 FROM dbo.DIM_OUTCOME
    UNION ALL SELECT 'DIM_PROMOTION', COUNT_BIG(*), 528 FROM dbo.DIM_PROMOTION
    UNION ALL SELECT 'DIM_DISTANCE', COUNT_BIG(*), 22 FROM dbo.DIM_DISTANCE
    UNION ALL SELECT 'DIM_ITEM', COUNT_BIG(*), 218 FROM dbo.DIM_ITEM
    UNION ALL SELECT 'FACT_ORDER', COUNT_BIG(*), 21321 FROM dbo.FACT_ORDER
    UNION ALL SELECT 'BRIDGE_ORDER_ITEM', COUNT_BIG(*), 38150 FROM dbo.BRIDGE_ORDER_ITEM
) AS checks;

SELECT COUNT_BIG(*) AS ORDERS,
       COUNT(DISTINCT SOURCE_ORDER_ID) AS DISTINCT_SOURCE_ORDERS,
       SUM(TOTAL) AS TOTAL_RS,
       COUNT(RATING_VALUE) AS RATED_ORDERS
FROM dbo.FACT_ORDER;
-- Expected: 21321, 21321, 14554058.14, 2491.

SELECT COUNT_BIG(*) AS ORDER_ITEM_PAIRS,
       COUNT(DISTINCT SOURCE_ORDER_ID) AS ORDERS_WITH_ITEMS,
       SUM(CAST(ITEM_QUANTITY AS BIGINT)) AS FOOD_UNITS
FROM dbo.BRIDGE_ORDER_ITEM;
-- Expected: 38150, 21321, 41287.

SELECT COUNT_BIG(*) AS ORPHAN_FACT_ROWS
FROM dbo.FACT_ORDER AS f
LEFT JOIN dbo.DIM_DATE AS d ON d.FULL_DATE = f.FULL_DATE
LEFT JOIN dbo.DIM_TIME AS t ON t.HOUR_NUMBER = f.HOUR_NUMBER
LEFT JOIN dbo.DIM_RESTAURANT AS r ON r.RESTAURANT_ID = f.RESTAURANT_ID
LEFT JOIN dbo.DIM_CUSTOMER AS c ON c.SOURCE_CUSTOMER_ID = f.SOURCE_CUSTOMER_ID
LEFT JOIN dbo.DIM_OUTCOME AS o ON o.OUTCOME_ID = f.OUTCOME_ID
LEFT JOIN dbo.DIM_PROMOTION AS p ON p.DISCOUNT_CONSTRUCT = f.DISCOUNT_CONSTRUCT
LEFT JOIN dbo.DIM_DISTANCE AS x ON x.DISTANCE = f.DISTANCE
WHERE d.FULL_DATE IS NULL OR t.HOUR_NUMBER IS NULL OR r.RESTAURANT_ID IS NULL
   OR c.SOURCE_CUSTOMER_ID IS NULL OR o.OUTCOME_ID IS NULL
   OR p.DISCOUNT_CONSTRUCT IS NULL OR x.DISTANCE IS NULL;
-- Expected: 0.

SELECT COUNT_BIG(*) AS ORPHAN_BRIDGE_ROWS
FROM dbo.BRIDGE_ORDER_ITEM AS b
LEFT JOIN dbo.FACT_ORDER AS f ON f.SOURCE_ORDER_ID = b.SOURCE_ORDER_ID
LEFT JOIN dbo.DIM_ITEM AS i ON i.ITEMS_IN_ORDER = b.ITEMS_IN_ORDER
WHERE f.SOURCE_ORDER_ID IS NULL OR i.ITEMS_IN_ORDER IS NULL;
-- Expected: 0.

SELECT COUNT_BIG(*) AS ORDERS_WITH_TOTAL_DISCREPANCY,
       MAX(ABS(BILL_SUBTOTAL + PACKAGING_CHARGES - DISCOUNT_TOTAL - TOTAL)) AS MAX_DIFFERENCE_RS
FROM dbo.FACT_ORDER
WHERE BILL_SUBTOTAL + PACKAGING_CHARGES - DISCOUNT_TOTAL <> TOTAL;
-- Expected: 18, 0.01; preserve the source values.
